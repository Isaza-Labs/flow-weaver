    public static async Task SeedAsync(IServiceScopeFactory scopeFactory, ILogger logger)
    {
        using var scope = scopeFactory.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();

        await SeedDefaultsAsync(db, logger);

    }

    private static async Task SeedDefaultsAsync(AppDbContext db, ILogger logger)
    {
        // Same advisory-lock pattern DefaultSnippetsSeedService uses.
        // Two concurrent boots must not double-insert the baseline.
        const long lockKey = 0x5311_9E75_0000_0002;
        await using var tx = await db.Database.BeginTransactionAsync();
        try
        {
            await db.Database.ExecuteSqlRawAsync(
                "SELECT pg_advisory_xact_lock({0})", lockKey);

            // Pull every row (active or not) so we can detect "admin
            // deleted this seed entry" and skip re-inserting it.
            var existing = await db.VendorCommands
                .Select(v => new { v.DeviceType, v.Kind, v.Value, v.IsActive })
                .ToListAsync();

            var seenAny = existing.Select(e => (e.DeviceType, e.Kind, e.Value))
                .ToHashSet();

            var now = DateTime.UtcNow;
            var inserted = 0;
            foreach (var catalog in Catalogs)
            {
                foreach (var entry in catalog.Entries)
                {
                    var key = (catalog.DeviceType, entry.Kind, entry.Value);
                    // Already present (active OR soft-deleted) → leave alone.
                    if (seenAny.Contains(key)) continue;

                    db.VendorCommands.Add(new VendorCommandModel
                    {
                        VendorCommandId = Guid.NewGuid(),
                        DeviceType = catalog.DeviceType,
                        VendorFamily = catalog.VendorFamily,
                        Kind = entry.Kind,
                        Value = entry.Value,
                        Source = VendorCommandModel.SourceSeed,
                        IsActive = true,
                        CreatedAt = now,
                        UpdatedAt = now,
                    });
                    inserted++;
                }
            }

            if (inserted > 0)
            {
                await db.SaveChangesAsync();
                await tx.CommitAsync();
                logger.LogInformation(
                    "Seeded {Count} vendor_command(s)",
                    inserted);
            }
            else
            {
                await tx.CommitAsync();
            }
        }
        catch
        {
            await tx.RollbackAsync();
            throw;
        }
    }
