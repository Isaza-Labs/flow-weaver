// cisco_nxos, juniper_junos, arista_eos, nokia_sros, nokia_srl, huawei,
// fortinet, linux). The baseline lands at first boot; admins extend it
// via the /vendor-commands UI.
//
// Idempotent by (DeviceType, Kind, Value): existing rows are
// left alone, missing rows are inserted. Rows the admin deleted (Source
// stays "seed" but IsActive=false) are NOT re-added — that would defeat
// the point of letting admins curate the catalog.
